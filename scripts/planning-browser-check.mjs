import assert from 'node:assert/strict'
export async function checkPlanning({phone,desktop,saved,db}) {
  const p=phone.page,d=desktop.page
  const current=async()=>(await db.query('select public.planner_snapshot() value')).rows[0].value
  const refresh=async page=>{await page.getByRole('button',{name:'获取最新数据',exact:true}).click();await page.waitForFunction(()=>[...document.querySelectorAll('button')].some(b=>b.textContent==='获取最新数据'&&!b.disabled))}
  const save=async page=>{await page.getByRole('button',{name:'保存到云端',exact:true}).click();await saved(page)}
  await p.getByRole('link',{name:'待办',exact:true}).click()
  await p.getByRole('button',{name:'收集一次性待办',exact:true}).click()
  await p.getByLabel('待办名称',{exact:true}).fill('完成课程报告')
  phone.mode('lost');await p.getByRole('button',{name:'保存到云端',exact:true}).click()
  await p.getByRole('button',{name:'确认并重试原请求',exact:true}).click();await saved(p)
  await p.getByRole('button',{name:'全部待办',exact:true}).click()
  await p.getByRole('heading',{name:'完成课程报告',exact:true}).waitFor()
  await p.getByText('待估算',{exact:true}).waitFor()
  assert.equal((await current()).todos.length,1)
  await p.getByRole('button',{name:'本周计划',exact:true}).click()
  await p.getByLabel('选择执行周',{exact:true}).fill('2026-11-02')
  await p.getByRole('button',{name:'编辑常规可用时间模板',exact:true}).click()
  for(const day of ['一','二','三','四','五']) {
    const details=p.locator('.availability-picker details').filter({has:p.locator('summary').filter({hasText:`周${day} ·`})})
    await details.locator('summary').click()
    for(const span of ['08:00–09:00','09:00–10:00','10:00–11:00','11:00–12:00']) await details.getByLabel(span,{exact:true}).check()
  }
  await save(p)
  await p.getByRole('button',{name:'编辑本周计划',exact:true}).click()
  const firstTask=(await current()).tasks[0]
  await p.getByLabel('从任务池或待办加入本周重点',{exact:true}).selectOption(`task:${firstTask.id}`)
  await p.getByRole('button',{name:'加入本周重点',exact:true}).click()
  await p.getByLabel('预计投入（分钟）',{exact:true}).fill('1440')
  await p.getByLabel(/本周新增量/).fill('30')
  await p.getByLabel('下周可带入草稿（须重新确认目标）',{exact:true}).check()
  await p.getByText('计划超出 4 小时，可以调整或保留。建议初期承诺约 80% 可用时间，不作为硬性上限。',{exact:true}).waitFor()
  assert.equal(await p.getByLabel('从任务池或待办加入本周重点').locator(`option[value="task:${firstTask.id}"]`).count(),0)
  await p.getByLabel('确认初始计划，留存此次目标作为周初参照',{exact:true}).check()
  await save(p)
  await d.getByRole('link',{name:'待办',exact:true}).click();await refresh(d)
  await d.getByLabel('选择执行周',{exact:true}).fill('2026-11-02')
  await d.getByRole('button',{name:'编辑本周计划',exact:true}).click()
  await d.getByLabel(/本周新增量/).fill('15')
  await p.getByRole('button',{name:'编辑本周计划',exact:true}).click()
  await p.getByLabel(/本周新增量/).fill('10')
  await save(p)
  await d.getByRole('button',{name:'保存到云端',exact:true}).click()
  await d.getByRole('alert').filter({hasText:'云端已有更新'}).waitFor()
  assert.equal(await d.getByLabel(/本周新增量/).inputValue(),'15')
  await refresh(d)
  await d.getByRole('button',{name:'已核对，将此输入应用到最新版本',exact:true}).click()
  await save(d)
  const confirmed=(await current()).weekPlans[0]
  assert.equal(confirmed.initialEntries[0].targetUnits,'30');assert.equal(confirmed.entries[0].targetUnits,'15');assert.equal(confirmed.history.length,3)
  await refresh(p)
  await p.getByLabel('选择执行周',{exact:true}).fill('2026-11-09')
  await p.getByRole('button',{name:'从上周带入已勾选的草稿',exact:true}).click()
  assert.equal(await p.getByLabel(/本周新增量/).inputValue(),'15')
  assert.equal(await p.getByLabel('确认初始计划，留存此次目标作为周初参照').isChecked(),false)
  await p.getByLabel('从任务池或待办加入本周重点',{exact:true}).selectOption(`todo:${(await current()).todos[0].id}`)
  await p.getByRole('button',{name:'加入本周重点',exact:true}).click()
  const todoEditor=p.getByRole('region',{name:'编辑 完成课程报告',exact:true})
  await todoEditor.getByLabel('预计投入（分钟）',{exact:true}).fill('60')
  await p.getByText('本周可用时间例外',{exact:true}).click()
  const monday=p.locator('.availability-picker details').filter({has:p.locator('summary').filter({hasText:'周一 ·'})})
  await monday.locator('summary').click();await monday.getByLabel('08:00–09:00',{exact:true}).uncheck()
  await save(p)
  let state=await current()
  assert.equal(state.weekPlans[1].confirmedAt,null);assert.equal(state.weekPlans[1].entries.length,2)
  assert.notEqual(state.weekPlans[1].entries[0].id,state.weekPlans[0].entries[0].id)
  assert.deepEqual(state.weekPlans[0],confirmed)
  const template=structuredClone(state.availabilityTemplate)
  await p.getByRole('button',{name:'全部待办',exact:true}).click()
  await p.getByText('执行周：2026-11-09',{exact:true}).waitFor()
  await p.getByRole('button',{name:'编辑待办',exact:true}).click()
  await p.getByLabel('待办备注',{exact:true}).fill('断网后保留输入')
  phone.mode('offline');await p.getByRole('button',{name:'保存到云端',exact:true}).click()
  await p.getByRole('button',{name:'确认并重试原请求',exact:true}).waitFor()
  assert.equal(await p.getByLabel('待办备注',{exact:true}).inputValue(),'断网后保留输入')
  phone.mode('normal');await p.getByRole('button',{name:'确认并重试原请求',exact:true}).click();await saved(p)
  await p.getByRole('button',{name:'本周计划',exact:true}).click()
  await p.getByLabel('选择执行周',{exact:true}).fill('2026-11-16')
  await p.getByRole('button',{name:'编辑本周计划',exact:true}).click();await save(p)
  state=await current();assert.deepEqual(state.weekPlans[2].availability,template)
  await p.getByRole('button',{name:'编辑常规可用时间模板',exact:true}).click()
  const mondayTemplate=p.locator('.availability-picker details').filter({has:p.locator('summary').filter({hasText:'周一 ·'})})
  await mondayTemplate.locator('summary').click();await mondayTemplate.getByRole('button',{name:'清空周一可用时间',exact:true}).click();await save(p)
  assert.deepEqual((await current()).weekPlans,state.weekPlans)
  await p.getByRole('button',{name:'编辑本周计划',exact:true}).click()
  await p.getByRole('link',{name:'日历',exact:true}).click()
  await p.getByText('待办中有未保存计划，切回待办可继续编辑。',{exact:true}).waitFor()
  await p.getByRole('link',{name:'待办',exact:true}).click()
  await p.getByRole('button',{name:'取消计划编辑',exact:true}).click()
  for(const width of [320,360,430,1280]) {
    await p.setViewportSize({width,height:900})
    assert.equal(await p.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),true,`planning overflow ${width}`)
  }
  await p.setViewportSize({width:360,height:900});await p.screenshot({path:'work/planning-mobile.png',fullPage:true})
  await d.setViewportSize({width:1280,height:900});await refresh(d);await d.screenshot({path:'work/planning-desktop.png',fullPage:true})
  console.log('PASS stage-5A browser simulation: unassigned/estimated todos, 20h capacity/24h budget, unique task/week, baseline and adjustment history, stale edit/rebase, lost response and offline draft retry, next-week draft, isolated week exceptions/template/history, page draft retention and 320/360/430/1280 layouts. NOT real Supabase or Android.')
}
